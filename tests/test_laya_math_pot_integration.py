"""The Laya router/scorer wiring and the program-of-thought math gate compose (the merge of two independent builds)."""
from __future__ import annotations

from gwaya.gwenlaya import GwenLaya, Tier
from gwaya.domains.task import CheckResult


def _tier(name, answer, pot):
    calls = []

    def gen(prompt, domain):
        calls.append(domain)
        return pot if domain == "math_pot" else answer
    return Tier(name, gen), calls


def test_pot_verified_math_stays_verified_with_router_and_scorer(monkeypatch):
    import gwaya.sandbox as sb
    monkeypatch.setattr(sb, "run_in_sandbox", lambda *a, **k: (True, "12\n", "", False))
    t, calls = _tier("qwen3.5-2b-bf16", "so the answer is \\boxed{12}", "```python\nprint(12)\n```")
    seen = {}
    g = GwenLaya([t], router=lambda p, d: {"qwen3.5-2b-bf16": 0.9},
                 scorer=lambda f: seen.setdefault("called", True) and 0.1, tau_route=0.5, route_policy="start_at")
    out = g.answer("What is 3*4? Put the final answer in \\boxed{}.", "math")
    assert out["verdict"] == "VERIFIED" and out["answer"].endswith("\\boxed{12}")
    assert calls == ["math", "math_pot"]  # the program was generated by the same tier, once


def test_no_boxed_answer_never_generates_a_program_under_the_router(monkeypatch):
    t, calls = _tier("qwen3.5-2b-bf16", "I think it is twelve", "```python\nprint(12)\n```")
    g = GwenLaya([t], router=lambda p, d: {"qwen3.5-2b-bf16": 0.9}, scorer=lambda f: 0.99, tau_route=0.5,
                 route_policy="start_at")
    out = g.answer("What is 3*4? Put the final answer in \\boxed{}.", "math")
    assert out["verdict"] != "VERIFIED" and calls == ["math"]
