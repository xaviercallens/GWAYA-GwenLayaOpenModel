# ── spend ────────────────────────────────────────────────────────────────────────────────────────────────────────

def spend() -> dict:
    Lg = [json.loads(l) for l in open(LEDGER) if l.strip()]
    if len(Lg) < LINES_3_10:
        raise SystemExit("ledger shorter than the 3.10.0 ledger")
    t310 = round(sum(x["usd_estimate"] for x in Lg[:LINES_3_10]), 4)
    assert abs(t310 - TOTAL_3_10) < 1e-4, (t310, TOTAL_3_10)
    new = Lg[LINES_3_10:]
    return {"lines_total": len(Lg), "total_usd": round(sum(x["usd_estimate"] for x in Lg), 4), "lines_3_10": LINES_3_10, "total_3_10": t310,
            "lines_new": len(new), "total_new": round(sum(x["usd_estimate"] for x in new), 4), "last_ts": Lg[-1]["ts"], "last_item": Lg[-1]["item"],
            "new_items": {x["item"]: {"ts": x["ts"], "seconds": x["seconds"], "usd": x["usd_estimate"], "accel": x["accel"], "price_source": x["price_source"]} for x in new}}


