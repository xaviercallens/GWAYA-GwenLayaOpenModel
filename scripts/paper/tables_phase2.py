def fit(tex: str) -> str:
    tex = tex.replace("\\begin{tabular}", "\\resizebox{\\textwidth}{!}{%\n\\begin{tabular}")
    return tex.replace("\\end{tabular}", "\\end{tabular}}")


def a30_largest(curve: dict) -> tuple | None:
    """Largest 0.1-step rank prefix with precision >= 0.84 and Wilson lower bound >= 0.80 (the A30 criterion)."""
    best = None
    for k, v in sorted(curve.items(), key=lambda kv: float(kv[0])):
        if v["precision"] >= 0.84 and v["wilson"][0] >= 0.80:
            best = (float(k), v["precision"], v["wilson"])
    return best


