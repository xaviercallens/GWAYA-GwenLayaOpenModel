#!/usr/bin/env python
"""Write the generated tables and macros of the phase-3 section (revision 3.13.0 draft); no result value is typed by hand.

Inputs (read-only):
  results/gwenlaya_v4/phase3/v2_dev.json        Verifier V2 dev readout (A33.4), rules (a) and (b)
  results/gwenlaya_v4/phase3/v2_sealed_G.json   the single sealed read on G (27B only)
  $GWAYA_DATA_ROOT/spend_ledger.jsonl           spend ledger (read at build time)
Outputs: papers/tables_phase3.tex, papers/numbers3130.tex (macros), results/gwenlaya_v4/spend_summary_3130.json
"""
from __future__ import annotations

import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = Path(os.environ.get("GWAYA_DATA_ROOT", "/mnt/data/home/xavkal/gwaya-data"))
RES = ROOT / "results/gwenlaya_v4"
P3 = RES / "phase3"
TIERS = ("qwen3.5-2b-bf16", "qwen3.5-4b-bf16", "qwen3.5-9b-bf16", "qwen3.5-27b-bf16")
SH = {"qwen3.5-2b-bf16": "2B", "qwen3.5-4b-bf16": "4B", "qwen3.5-9b-bf16": "9B", "qwen3.5-27b-bf16": "27B"}
LINES_3_12, TOTAL_3_12 = 35, 26.3314   # ledger lines and sum read by revision 3.12.0 (papers/numbers3120.tex)
HEAD = "% generated by scripts/paper/tables_phase3.py - do not edit\n"


def n(x, d: int = 3, sign: bool = False) -> str:
    if x is None:
        return "n/a"
    s = f"{abs(x):.{d}f}"
    if x < 0:
        return "$-" + s + "$"
    return ("$+" + s + "$") if sign else s


def wl(p, iv, d: int = 3) -> str:
    if p is None or iv is None or iv[0] is None:
        return "n/a"
    return f"{n(p, d)} [{n(iv[0], d)}, {n(iv[1], d)}]"


def fit(tex: str) -> str:
    tex = tex.replace("\\begin{tabular}", "\\resizebox{\\textwidth}{!}{%\n\\begin{tabular}")
    return tex.replace("\\end{tabular}", "\\end{tabular}}")


def table_dev(D: dict) -> str:
    t = ("\\begin{table}[!htbp]\\centering\\scriptsize\\setlength{\\tabcolsep}{3pt}\n"
         "\\caption{A33 development readout of Verifier V2 on F Python (407 tasks per tier), five-fold grouped CV with the certificate "
         "inside each fold (risk 0.10, $\\delta=0.10$, thresholds $\\{0.95,0.925,0.90,0.875,0.85\\}$ in that order; \\code{v2_dev.json}). "
         "Synthesized tests were written by the 27B for every tier. Pools: greedy + 8 samples (2B, 4B, 9B), greedy + 4 samples (27B), so the 27B "
         "``any correct'' is over 5 candidates and the others over 9. Certified coverage is the mean over folds of the accepted share of the "
         "test fold; ``prec.'' is pooled over folds. $\\Delta$ is V2 minus B0 correct accepted tasks at coverage 0.40 on out-of-fold scores, with a "
         "paired cluster-bootstrap 95\\% interval. Rule (a): coverage gain $\\ge0.10$ and interval above zero.}\\label{tab:p3-dev}\n"
         "\\begin{tabular}{lcccccccc}\\toprule\ntier & greedy & any correct & V2 cert.\\ cov. & V2 prec. & B0 cert.\\ cov. & B0 prec. & $\\Delta$ correct@0.40 [CI] & rule (a)\\\\\\midrule\n")
    for tr in TIERS:
        x = D["tiers"][tr]
        d = x["paired_correct_diff_cov40"]
        t += (f"{SH[tr]} & {n(x['greedy_pass'])} & {n(x['oracle_any'])} & {n(x['V2']['mean_cert_coverage'])} & {n(x['V2']['pooled_precision'])} & "
              f"{n(x['B0']['mean_cert_coverage'])} & {n(x['B0']['pooled_precision'])} & {n(d['mean'], 1, True)} [{d['ci'][0]:.0f}, {d['ci'][1]:.0f}] & "
              f"{'met' if x['rule_a']['lever'] else 'not met'}\\\\\n")
    b = D["rule_b"]
    t += ("\\bottomrule\\end{tabular}\n"
          f"\\par\\smallskip\\parbox{{0.95\\textwidth}}{{\\scriptsize Rule (b), 27B against the 9B on the {b['n_common']} common tasks: V2 certified-coverage gain "
          f"{n(b['coverage_gain'], 3, True)}, paired correct@0.40 difference {n(b['paired_correct_diff_cov40']['mean'], 1, True)} "
          f"[{b['paired_correct_diff_cov40']['ci'][0]:.0f}, {b['paired_correct_diff_cov40']['ci'][1]:.0f}]: "
          f"\\textbf{{{'met' if b['lever'] else 'not met'}}}.}}\n\\end{{table}}\n")
    return fit(t)


def table_sealed(S: dict) -> str:
    x = S["tiers"]["qwen3.5-27b-bf16"]
    t = ("\\begin{table}[!htbp]\\centering\\scriptsize\\setlength{\\tabcolsep}{3pt}\n"
         f"\\caption{{The sealed read on G, 27B only ({x['n_G']} Python tasks; policies fitted on all {x['n_F']} F tasks, isotonic calibrator on F out-of-fold scores; "
         "\\code{v2_sealed_G.json}). The fixed-sequence test stops at the first threshold that fails; no threshold in the declared order certifies for either policy, "
         "so the certified coverage is 0 and the goal is \\textbf{not met}. Precision columns are descriptive rank-curve points: precision of the top 30\\%, 40\\% and 50\\% of "
         "tasks by score [Wilson 95\\%].}\\label{tab:p3-sealed}\n"
         "\\begin{tabular}{lcccc}\\toprule\npolicy & certified threshold / coverage & top 30\\% & top 40\\% & top 50\\%\\\\\\midrule\n")
    for name, lab in (("V2", "V2 (own-test selection)"), ("B0_D3", "B0 = D3 \\code{lr|core} on greedy")):
        v = x[name]
        c = v["rank_curve"]
        t += (f"{lab} & {'none' if v['certified_threshold'] is None else v['certified_threshold']} / {n(v['coverage'])} & "
              + " & ".join(wl(c[k]['precision'], c[k]['wilson']) for k in ("0.3", "0.4", "0.5")) + "\\\\\n")
    g = x["gate_only"]
    t += (f"gate only (greedy gate VERIFIED) & coverage {n(g['coverage'])} & \\multicolumn{{3}}{{c}}{{precision {wl(g['correct'] / g['n_accept'], g['wilson'])} at {g['n_accept']} accepted}}\\\\\n")
    a = x["accept_all"]
    t += f"accept all (greedy) & coverage 1 & \\multicolumn{{3}}{{c}}{{precision {wl(a['precision'], a['wilson'])}}}\\\\\n"
    t += f"oracle (any of 5 correct) & \\multicolumn{{4}}{{c}}{{{n(x['oracle_any'])}}}\\\\\n\\bottomrule\\end{{tabular}}\n"
    t += "\\par\\smallskip\\parbox{0.95\\textwidth}{\\scriptsize Fixed-sequence ladder (threshold: accepted, errors, exact-binomial $p$ against risk 0.10; certify needs $p\\le0.10$): "
    for name in ("V2", "B0_D3"):
        t += name.replace("_", "\\_") + ": " + "; ".join(
            f"{l['threshold']}: {l['n_accept']}, {l['errors']}, {n(l['binom_p'], 2) if l['binom_p'] is not None else 'n/a'}" for l in x[name]["ltt_ladder"]) + ". "
    t += "}\n\\end{table}\n"
    return fit(t)


def spend() -> dict:
    rows = [json.loads(l) for l in (DATA / "spend_ledger.jsonl").read_text().splitlines() if l.strip()]
    new = rows[LINES_3_12:]
    return {"lines": len(rows), "total": round(sum(r["usd_estimate"] for r in rows), 4),
            "last_ts": rows[-1]["ts"], "new_lines": len(new), "new_total": round(sum(r["usd_estimate"] for r in new), 4),
            "new_items": [{"item": r["item"], "usd": r["usd_estimate"], "seconds": r["seconds"], "zone": r["zone"], "accel": r["accel"]} for r in new],
            "total_3_12": TOTAL_3_12, "lines_3_12": LINES_3_12}


def table_spend(sp: dict) -> str:
    t = ("\\begin{table}[!htbp]\\centering\\scriptsize\n"
         "\\caption{Ledger lines added after revision 3.12.0 (list-price estimates, not the bill; \\code{spend_summary_3130.json}). The two \\code{p3-t5-2005xx} lines are two "
         "identical T5 VMs that ran in parallel (same job, same 27B outputs, same 35B failure); only the first one's outputs were used.}\\label{tab:spend3130}\n"
         "\\begin{tabular}{llrr}\\toprule\nitem & slice & seconds & USD\\\\\\midrule\n")
    for r in sp["new_items"]:
        t += f"\\code{{{r['item'].replace('_', chr(92) + '_')}}} & {r['accel']} ({r['zone']}) & {r['seconds']} & {r['usd']:.4f}\\\\\n"
    t += f"\\midrule total & & & {sp['new_total']:.4f}\\\\\n\\bottomrule\\end{{tabular}}\\end{{table}}\n"
    return t


def main() -> None:
    D = json.loads((P3 / "v2_dev.json").read_text())
    S = json.loads((P3 / "v2_sealed_G.json").read_text())
    sp = spend()
    (ROOT / "papers/tables_phase3.tex").write_text(HEAD + table_dev(D) + "\n" + table_sealed(S) + "\n" + table_spend(sp))
    m = {"PThreeLines": sp["lines"], "PThreeTotal": f"{sp['total']:.2f}", "PThreeShare": f"{100 * sp['total'] / 50:.0f}",
         "PThreeNewLines": sp["new_lines"], "PThreeNewTotal": f"{sp['new_total']:.2f}", "PThreeLastTs": sp["last_ts"]}
    (ROOT / "papers/numbers3130.tex").write_text(HEAD + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in m.items()))
    (RES / "spend_summary_3130.json").write_text(json.dumps(sp, indent=1))
    print("wrote papers/tables_phase3.tex, papers/numbers3130.tex", m)


if __name__ == "__main__":
    main()
