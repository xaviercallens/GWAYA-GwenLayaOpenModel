def n(x, d: int = 3, sign: bool = False) -> str:
    if x is None:
        return "n/a"
    s = f"{abs(x):.{d}f}"
    if x < 0:
        return "$-" + s + "$"
    return ("$+" + s + "$") if sign else s


def ci(c: dict | None, d: int = 3, sign: bool = False) -> str:
    if not c or c.get("point") is None:
        return "n/a"
    if c.get("lo") is None:
        return n(c["point"], d, sign)
    return f"{n(c['point'], d, sign)} [{n(c['lo'], d, sign)}, {n(c['hi'], d, sign)}]"


def esc(s: str) -> str:
    return s.replace("_", "\\_").replace("&", "\\&")


def jl(p: Path) -> list[dict]:
    return [json.loads(l) for l in p.read_text().splitlines() if l.strip()]


