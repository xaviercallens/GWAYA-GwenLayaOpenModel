def forbidden_breakdown() -> dict:
    from gwaya.lean_gate import lexical_flaws
    out: dict = {"note": "which lexical rule of gwaya/lean_gate.py::lexical_flaws fires on the stored text of every row whose reason is forbidden_construct; "
                         "offline, no Lean process; 'unexplained' = rows with that reason but no flaw found by the function",
                 "sets": {}}
    for name, pat in (("A18_minif2f_test", RES / "lean_a18/scored_greedy_v3/scored_raw_*.jsonl"), ("F_minif2f_valid", F / "lean_scored/scored_raw_*.jsonl")):
        out["sets"][name] = {}
        for p in sorted(glob.glob(str(pat))):
            rows = jl(Path(p))
            cnt: dict[str, int] = {}
            n_forb = unexplained = 0
            for r in rows:
                if r.get("reason") == "forbidden_construct":
                    n_forb += 1
                    fl = lexical_flaws(r["text"])
                    unexplained += not fl
                    for f in fl:
                        cnt[f] = cnt.get(f, 0) + 1
            out["sets"][name][Path(p).stem.replace("scored_raw_", "")] = {"rows": len(rows), "forbidden_construct": n_forb,
                                                                          "flaws": cnt, "unexplained": unexplained}
    return out


