def spend() -> dict:
    Lg = [json.loads(l) for l in open(LEDGER) if l.strip()]
    if len(Lg) < LINES_3_9:
        raise SystemExit("ledger shorter than the 3.9.0 ledger")
    total = round(sum(x["usd_estimate"] for x in Lg), 4)
    t39 = round(sum(x["usd_estimate"] for x in Lg[:LINES_3_9]), 4)
    assert abs(t39 - TOTAL_3_9) < 1e-4, (t39, TOTAL_3_9)
    new = Lg[LINES_3_9:]
    return {"lines_total": len(Lg), "total_usd": total, "lines_3_9": LINES_3_9, "total_3_9": t39, "lines_new": len(new),
            "total_new": round(sum(x["usd_estimate"] for x in new), 4), "last_ts": Lg[-1]["ts"], "last_item": Lg[-1]["item"],
            "a18_generation_lines_in_3_9": 2,
            "new_items": {x["item"]: {"ts": x["ts"], "seconds": x["seconds"], "usd": x["usd_estimate"], "accel": x["accel"]} for x in new},
            "note": "lines after 27 were written after the 3.9.0 build (A21 generation of F on 2B/4B/9B, the frozen Laya on F, the A22 layout ablation); "
                    "the A18 Lean generation lines (26, 27) were already counted in 3.9.0"}


