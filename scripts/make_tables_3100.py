def sha_tree(rel: str) -> str:
    return hashlib.sha256((ROOT / rel).read_bytes()).hexdigest()


def write_hashes(S: dict) -> None:
    out = HEAD
    for rel in HASHED:
        out += f"\\url{{{rel}}} & \\texttt{{\\seqsplit{{{sha_tree(rel)}}}}}\\\\\n"
    # the 3.10.0 hashed set reads papers/*3100.tex, so the generator must run twice (tables first); the second run is the record
    out += (f"\\url{{spend_ledger.jsonl ({S['lines_total']} lines, as read for 3.10.0; a living file)}} & "
            f"\\texttt{{\\seqsplit{{{hashlib.sha256(LEDGER.read_bytes()).hexdigest()}}}}}\\\\\n")
    (ROOT / "papers/sha3100.tex").write_text(out)


