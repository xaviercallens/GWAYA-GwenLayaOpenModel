def cut_timeouts(scored_dir: Path) -> dict[str, int]:
    """Rows whose Lean check timed out although the generation was cut at the token limit (they are counted under 'truncated')."""
    out = {}
    for x in T4:
        p = scored_dir / f"scored_raw_{x}.jsonl"
        if p.exists():
            out[x] = sum(1 for r in jl(p) if r.get("reason") == "timeout" and r.get("finish_reason") == "length")
    return out


